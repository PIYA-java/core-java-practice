package branching2;

public class twentyone {

	public static void main(String[] args) {
		int choice=2;
		switch(choice)
		{
		case 1 : System.out.println("General Booking Ticket");
		break;
		case 2 : System.out.println("Sleeper Booking Ticket");
		break;
		case 3 : System.out.println("AC Booking Ticket");
		break;
		default : System.out.println("Invalid Choice");
	
		}

	}

}
