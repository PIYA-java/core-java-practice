package branching2;

public class twentytwo {

	public static void main(String[] args) {
		int room=1;
		switch(room)
		{
		case 1 : System.out.println("Single Room");
		break;
		case 2 : System.out.println("Double Room");
		break;
		case 3 : System.out.println("Deluxe Room");
		break;
		default : System.out.println("Room not available");
	
		}

	}

}
