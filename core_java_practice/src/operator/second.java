package operator;

public class second {

	public static void main(String[] args) {
		int a=10;
		a+=5;   //15
		System.out.println("a+=5 :"+a);
		a-=2;   //13
		System.out.println("a-=2 :"+a);
		a*=3;   //39
		System.out.println("a*=3 :"+a);
		a/=2;   //19.
		System.out.println("a/=2 :"+a);
		a%=4;   //3
		System.out.println("a%=4 :"+a);

	}

}
